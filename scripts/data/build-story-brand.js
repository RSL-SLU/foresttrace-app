#!/usr/bin/env node
/**
 * Builds api/_storyBrand.js: the logos for the story map's brand card, as
 * small embedded images, so a story page carries its branding with it (no
 * request back to the app, which a shared or downloaded page may not reach).
 *
 *   ForestTrace  client/public/logo-ft.png            trimmed to the mark +
 *                                                     wordmark (drops the
 *                                                     wide cream margin)
 *   SLU + RSL    client/public/rsl-logo-transparent.png
 *
 * Rendered at 2x the card's display height for sharp edges on HiDPI screens.
 *
 * Usage:  node scripts/data/build-story-brand.js
 * Re-run whenever either logo changes.
 */

const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'api', '_storyBrand.js');
const HEIGHT = 88; // 2x the 44px the card shows

async function webpDataUri(input, transform) {
  const buf = await transform(sharp(path.join(ROOT, input))).webp({ quality: 88, alphaQuality: 90 }).toBuffer();
  return { uri: `data:image/webp;base64,${buf.toString('base64')}`, bytes: buf.length };
}

(async () => {
  const forestTrace = await webpDataUri('client/public/logo-ft.png',
    (img) => img.trim({ threshold: 18 }).resize({ height: HEIGHT }));
  const sluRsl = await webpDataUri('client/public/rsl-logo-transparent.png',
    (img) => img.trim({ threshold: 10 }).resize({ height: HEIGHT }));

  const body = `// Generated by scripts/data/build-story-brand.js -- do not edit by hand.
// Logos for the story map's brand card (api/_storyRender.js), embedded so a
// story page is self-contained.
module.exports = {
  // The ForestTrace logo's own background, so the card matches it exactly
  BRAND_BG: '#FEFBF6',
  FORESTTRACE_LOGO: '${forestTrace.uri}',
  SLU_RSL_LOGO: '${sluRsl.uri}',
};
`;
  fs.writeFileSync(OUT, body);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ForestTrace ${Math.round(forestTrace.bytes / 1024)} KB, SLU+RSL ${Math.round(sluRsl.bytes / 1024)} KB`);
})().catch((err) => {
  console.error(err);
  process.exit(1);
});
